def main() -> None:
    # +/+ : 7 // 2 = 3, 7 % 2 = 1
    print(7 // 2)
    print(7 % 2)
    # -/+ : -7 // 2 = -4, -7 % 2 = 1
    print(-7 // 2)
    print(-7 % 2)
    # +/- : 7 // -2 = -4, 7 % -2 = -1
    print(7 // -2)
    print(7 % -2)
    # -/- : -7 // -2 = 3, -7 % -2 = -1
    print(-7 // -2)
    print(-7 % -2)


main()
